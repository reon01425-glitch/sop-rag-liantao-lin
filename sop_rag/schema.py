"""
Data models and schemas for SOPRAG.
Defines atomic SOP documents, Procedure Cards, Multi-view Graph elements,
Router outputs, and evaluation results.
"""

from typing import List, Dict, Any, Optional, Tuple
from pydantic import BaseModel, Field


class SOPStep(BaseModel):
    """A procedural step in an SOP Flow Graph."""
    step_id: str
    order: int
    text: str
    step_type: str = "action"  # "action" or "condition"
    branches: Optional[Dict[str, str]] = None  # e.g. {"true": "step_3", "false": "step_4"}
    tool_trigger: Optional[str] = None  # For agent-integrated execution (e.g. "call_agent", "email_agent")


class Entity(BaseModel):
    """An industrial entity extracted for the Entity Graph."""
    name: str
    category: str  # "alarm", "parameter", "equipment", "role", "system"
    attributes: Dict[str, Any] = Field(default_factory=dict)


class CausalRelation(BaseModel):
    """A causal transition in the Causal Graph."""
    cause_state: str
    effect_state: str
    relation_type: str = "causes"  # "causes", "prevents", "enables", "mitigates"


class FlowGraphData(BaseModel):
    """Local topological flow graph for an SOP."""
    sop_id: str
    steps: List[SOPStep]
    edges: List[Tuple[str, str]] = Field(default_factory=list)  # (step_id_from, step_id_to)


class ProcedureCard(BaseModel):
    """
    Procedure Card (PC_i) layer representation.
    PC_i = {Title(S_i), Abstract(S_i)} in V_Global
    Acts as the primary entry point for sparse activation.
    """
    sop_id: str
    domain: str
    title: str
    abstract: str
    metadata: Dict[str, Any] = Field(default_factory=dict)

    @property
    def full_text(self) -> str:
        return f"{self.title}: {self.abstract}"


class SOPDocument(BaseModel):
    """Raw / parsed atomic Standard Operating Procedure."""
    sop_id: str
    domain: str  # "data_center", "liquid_cooling", "building_management", "airline_services"
    document_id: str  # e.g. "DC-SOP-CRIT-005.A"
    version: str = "1.0"
    title: str
    scope: str
    pre_action_requirements: List[str] = Field(default_factory=list)
    raw_markdown: str
    
    # Graph expert extractions
    procedure_card: Optional[ProcedureCard] = None
    entities: List[Entity] = Field(default_factory=list)
    causal_states: List[str] = Field(default_factory=list)
    causal_relations: List[CausalRelation] = Field(default_factory=list)
    flow_graph: Optional[FlowGraphData] = None


class RouterWeights(BaseModel):
    """Attention weights allocated by the LLM Router w = [w_E, w_C, w_F]."""
    w_E: float = Field(..., description="Weight for Entity Graph Expert (equipment, alarms, parameters)")
    w_C: float = Field(..., description="Weight for Causal Graph Expert (why, diagnosis, root-cause)")
    w_F: float = Field(..., description="Weight for Flow Graph Expert (how, execution, step-by-step)")
    intent_summary: str = ""
    extracted_entities: List[str] = Field(default_factory=list)


class RetrievalScore(BaseModel):
    """Detailed score breakdown for a candidate SOP."""
    sop_id: str
    title: str
    final_score: float
    anchor_score: float  # Sim(Q, PC_i)
    entity_score: float  # R_E
    causal_score: float  # R_C
    flow_score: float    # R_F
    weights: RouterWeights


class GeneratedStep(BaseModel):
    """Linearized step generated by the structure-aware LLM."""
    step_num: int
    instruction: str
    condition: Optional[str] = None
    agent_action: Optional[str] = None


class SOPGenerationOutput(BaseModel):
    """Result of structure-aware generation."""
    sop_id: str
    title: str
    generated_response: str
    verified_steps: List[str]
    sop_quality_score: Dict[str, Any]  # has_step_by_step, is_precise, is_concise, is_clear, score
